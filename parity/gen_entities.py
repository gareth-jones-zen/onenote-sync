"""Writes src/OneNoteSync/Interim/PyHtmlEntities.g.cs from Python's own html.entities.html5, so the port's
html.unescape knows exactly the names Python's does (2,231, with and without the ";").

    python parity/gen_entities.py
"""

import html.entities
import pathlib
import sys

out = pathlib.Path(__file__).resolve().parent.parent / "src" / "OneNoteSync" / "Interim" / "PyHtmlEntities.g.cs"
BACKSLASH = chr(92)


def literal(text: str) -> str:
    units = text.encode("utf-16-le")
    codes = (int.from_bytes(units[i:i + 2], "little") for i in range(0, len(units), 2))
    return '"' + "".join(f"{BACKSLASH}u{code:04X}" for code in codes) + '"'


lines = [
    "// <auto-generated> by parity/gen_entities.py from Python "
    f"{sys.version_info.major}.{sys.version_info.minor}'s html.entities.html5. Don't edit by hand. </auto-generated>",
    "// Interim: belongs in background-tools-lib with PyHtml.",
    "namespace OneNoteSync.Interim;",
    "",
    "internal static class PyHtmlEntities",
    "{",
    "    /// <summary>Name, value, name, value... (names as html5 holds them: some with \";\", some without).</summary>",
    "    internal static readonly string[] Pairs =",
    "    [",
]
for name, value in sorted(html.entities.html5.items()):
    lines.append(f'        "{name}", {literal(value)},')
lines += ["    ];", "}", ""]
out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"{len(html.entities.html5)} entities -> {out}")
